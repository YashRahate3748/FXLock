CREATE TABLE customer_account (
    account_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    customer_id NUMBER NOT NULL,

    email VARCHAR2(200 CHAR) NOT NULL,

    login_password VARCHAR2(255 CHAR) NOT NULL,

    account_status VARCHAR2(20 CHAR)
        DEFAULT 'ACTIVE' NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP NOT NULL,

    updated_at TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_customer_account
        PRIMARY KEY (account_id),

    CONSTRAINT fk_account_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer (customer_id),

    CONSTRAINT uq_account_customer
        UNIQUE (customer_id),

    CONSTRAINT uq_account_email
        UNIQUE (email),

    CONSTRAINT ck_account_email_normalized
        CHECK (email = LOWER(TRIM(email))),

    CONSTRAINT ck_account_status
        CHECK (account_status IN ('ACTIVE', 'DISABLED'))
);


SELECT
    column_name,
    data_type,
    nullable
FROM user_tab_columns
WHERE table_name = 'CUSTOMER_ACCOUNT'
ORDER BY column_id;