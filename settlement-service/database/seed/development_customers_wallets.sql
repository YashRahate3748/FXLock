        CHECK
        (
            STATUS IN
            (
                'COMPLETED',
                'REJECTED',
                'FAILED'
            )
        )
);


/* ------------------------------------------------------------
   Only one COMPLETED settlement may exist per quote.

   Oracle function-based unique index:
   rows that are not COMPLETED produce NULL and are ignored.
   ------------------------------------------------------------ */

CREATE UNIQUE INDEX UQ_ONE_COMPLETED_SETTLEMENT
ON SETTLEMENT
(
    CASE
        WHEN STATUS = 'COMPLETED'
        THEN QUOTE_ID
        ELSE NULL
    END
);


