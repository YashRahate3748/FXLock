            )
        ),

    CONSTRAINT CK_OUTBOX_RETRY_COUNT
        CHECK (RETRY_COUNT >= 0),

    CONSTRAINT CK_OUTBOX_PAYLOAD_JSON
        CHECK (PAYLOAD IS JSON)
);


/* ============================================================
   13. PROCESSED EVENT
   Owner: M4

