        CHECK (BALANCE >= 0),

    CONSTRAINT CK_WALLET_STATUS
        CHECK (STATUS IN ('ACTIVE', 'BLOCKED', 'CLOSED'))
);


/* ============================================================
   3. FX CONFIGURATION
   Owner: M1 primarily
   Used by Rate + Quote services.

   Defaults:
   - EUR/USD
   - rate fetch = 15 seconds
   - max rate age = 90 seconds
   - quote validity = 60 seconds
   ============================================================ */

CREATE TABLE FX_CONFIG
(
    CONFIG_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    CURRENCY_PAIR VARCHAR2(10)
        NOT NULL,

    BASE_CURRENCY VARCHAR2(3)
        NOT NULL,

    QUOTE_CURRENCY VARCHAR2(3)
        NOT NULL,

    RATE_FETCH_INTERVAL_SECONDS NUMBER
        DEFAULT 15
        NOT NULL,

    MAX_RATE_AGE_SECONDS NUMBER
        DEFAULT 90
        NOT NULL,

    QUOTE_VALIDITY_SECONDS NUMBER
        DEFAULT 60
        NOT NULL,

    BUSINESS_SPREAD_BPS NUMBER(10,4)
        DEFAULT 20
        NOT NULL,

    MIN_TRANSACTION_AMOUNT NUMBER(19,4)
        DEFAULT 10
        NOT NULL,

    MAX_TRANSACTION_AMOUNT NUMBER(19,4)
        DEFAULT 100000
        NOT NULL,

    ANOMALY_THRESHOLD_PERCENT NUMBER(10,6)
        DEFAULT 0.5
        NOT NULL,

    QUOTING_ENABLED CHAR(1)
        DEFAULT 'Y'
        NOT NULL,

    ACTIVE_FLAG CHAR(1)
        DEFAULT 'Y'
        NOT NULL,

    CREATED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    UPDATED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_FX_CONFIG
        PRIMARY KEY (CONFIG_ID),

    CONSTRAINT UQ_FX_CONFIG_PAIR
        UNIQUE (CURRENCY_PAIR),

    CONSTRAINT CK_CONFIG_BASE
        CHECK (BASE_CURRENCY IN ('EUR', 'USD')),

    CONSTRAINT CK_CONFIG_QUOTE
        CHECK (QUOTE_CURRENCY IN ('EUR', 'USD')),

    CONSTRAINT CK_CONFIG_DIFFERENT_CURRENCIES
        CHECK (BASE_CURRENCY <> QUOTE_CURRENCY),

    CONSTRAINT CK_CONFIG_FETCH_INTERVAL
        CHECK (RATE_FETCH_INTERVAL_SECONDS > 0),

    CONSTRAINT CK_CONFIG_RATE_AGE
        CHECK (MAX_RATE_AGE_SECONDS > 0),

    CONSTRAINT CK_CONFIG_QUOTE_VALIDITY
        CHECK (QUOTE_VALIDITY_SECONDS > 0),

    CONSTRAINT CK_CONFIG_MIN_AMOUNT
        CHECK (MIN_TRANSACTION_AMOUNT > 0),

    CONSTRAINT CK_CONFIG_MAX_AMOUNT
        CHECK (MAX_TRANSACTION_AMOUNT >= MIN_TRANSACTION_AMOUNT),

    CONSTRAINT CK_CONFIG_ANOMALY_THRESHOLD
        CHECK (ANOMALY_THRESHOLD_PERCENT > 0),

    CONSTRAINT CK_CONFIG_QUOTING_ENABLED
        CHECK (QUOTING_ENABLED IN ('Y', 'N')),

    CONSTRAINT CK_CONFIG_ACTIVE
        CHECK (ACTIVE_FLAG IN ('Y', 'N'))
);


/* ============================================================
   4. MARKET RATE SNAPSHOT
   Owner: M1

   Stores every provider observation.
   A suspicious / invalid observation can be recorded without
   becoming the trusted cached rate.
   ============================================================ */

CREATE TABLE MARKET_RATE_SNAPSHOT
(
    RATE_SNAPSHOT_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    CURRENCY_PAIR VARCHAR2(10)
        NOT NULL,

    PROVIDER_NAME VARCHAR2(50)
        NOT NULL,

    MARKET_RATE NUMBER(20,10)
        NOT NULL,

    PROVIDER_TIMESTAMP TIMESTAMP WITH TIME ZONE,

    RECEIVED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    VALIDATION_STATUS VARCHAR2(20)
        NOT NULL,

    TRUSTED_FLAG CHAR(1)
        DEFAULT 'N'
        NOT NULL,

    MOVEMENT_PERCENT NUMBER(12,8),

    VALIDATION_REASON VARCHAR2(1000),

    CORRELATION_ID VARCHAR2(100),

    CREATED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_MARKET_RATE
        PRIMARY KEY (RATE_SNAPSHOT_ID),

    CONSTRAINT CK_MARKET_RATE_POSITIVE
        CHECK (MARKET_RATE > 0),

    CONSTRAINT CK_RATE_VALIDATION_STATUS
        CHECK
        (
            VALIDATION_STATUS IN
            (
                'TRUSTED',
                'SUSPICIOUS',
                'INVALID'
            )
        ),

    CONSTRAINT CK_RATE_TRUSTED_FLAG
        CHECK (TRUSTED_FLAG IN ('Y', 'N'))
);


/* ============================================================
   5. RATE ANOMALY
   Owner: M1

   Keeps anomaly/risk information separate from the raw rate.
   ============================================================ */

CREATE TABLE RATE_ANOMALY
(
    ANOMALY_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    RATE_SNAPSHOT_ID NUMBER
        NOT NULL,

    PREVIOUS_TRUSTED_RATE_ID NUMBER,

    MOVEMENT_PERCENT NUMBER(12,8),

    THRESHOLD_PERCENT NUMBER(12,8),

    STATUS VARCHAR2(30)
        DEFAULT 'OPEN'
        NOT NULL,

    REASON VARCHAR2(1000),

    REVIEWED_BY VARCHAR2(100),

    REVIEW_REASON VARCHAR2(1000),

    REVIEWED_AT TIMESTAMP WITH TIME ZONE,

    CREATED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_RATE_ANOMALY
        PRIMARY KEY (ANOMALY_ID),

    CONSTRAINT FK_ANOMALY_RATE
        FOREIGN KEY (RATE_SNAPSHOT_ID)
        REFERENCES MARKET_RATE_SNAPSHOT (RATE_SNAPSHOT_ID),

    CONSTRAINT FK_ANOMALY_PREVIOUS_RATE
        FOREIGN KEY (PREVIOUS_TRUSTED_RATE_ID)
        REFERENCES MARKET_RATE_SNAPSHOT (RATE_SNAPSHOT_ID),

    CONSTRAINT CK_ANOMALY_STATUS
        CHECK
        (
            STATUS IN
            (
                'OPEN',
                'ACKNOWLEDGED',
                'APPROVED',
                'REJECTED'
            )
        )
);


/* ============================================================
   6. FX QUOTE
   Owner: M2

   Financial values are immutable after quote creation.
   ============================================================ */

CREATE TABLE FX_QUOTE
(
    QUOTE_ID VARCHAR2(36),

    CUSTOMER_ID NUMBER NOT NULL,

    SOURCE_WALLET_ID NUMBER NOT NULL,
    TARGET_WALLET_ID NUMBER NOT NULL,

    RATE_SNAPSHOT_ID NUMBER NOT NULL,

    SOURCE_CURRENCY VARCHAR2(3) NOT NULL,
    TARGET_CURRENCY VARCHAR2(3) NOT NULL,

    SOURCE_AMOUNT NUMBER(19,4) NOT NULL,

    MARKET_RATE NUMBER(20,10) NOT NULL,

    CUSTOMER_RATE NUMBER(20,10) NOT NULL,

    APPLIED_SPREAD_BPS NUMBER(10,4) NOT NULL,

    TARGET_AMOUNT NUMBER(19,4) NOT NULL,

    STATUS VARCHAR2(20)
        DEFAULT 'OPEN'
        NOT NULL,

    CREATED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    EXPIRES_AT TIMESTAMP WITH TIME ZONE
        NOT NULL,

    CANCELLED_AT TIMESTAMP WITH TIME ZONE,

    SETTLED_AT TIMESTAMP WITH TIME ZONE,

    CORRELATION_ID VARCHAR2(100),

    CONSTRAINT PK_FX_QUOTE
        PRIMARY KEY (QUOTE_ID),

    CONSTRAINT FK_QUOTE_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER (CUSTOMER_ID),

    CONSTRAINT FK_QUOTE_SOURCE_WALLET
        FOREIGN KEY (SOURCE_WALLET_ID)
        REFERENCES WALLET (WALLET_ID),

    CONSTRAINT FK_QUOTE_TARGET_WALLET
        FOREIGN KEY (TARGET_WALLET_ID)
        REFERENCES WALLET (WALLET_ID),

    CONSTRAINT FK_QUOTE_RATE
        FOREIGN KEY (RATE_SNAPSHOT_ID)
        REFERENCES MARKET_RATE_SNAPSHOT (RATE_SNAPSHOT_ID),

    CONSTRAINT CK_QUOTE_SOURCE_CURRENCY
        CHECK (SOURCE_CURRENCY IN ('EUR', 'USD')),

    CONSTRAINT CK_QUOTE_TARGET_CURRENCY
        CHECK (TARGET_CURRENCY IN ('EUR', 'USD')),

    CONSTRAINT CK_QUOTE_CURRENCY_DIFFERENT
        CHECK (SOURCE_CURRENCY <> TARGET_CURRENCY),

    CONSTRAINT CK_QUOTE_SOURCE_AMOUNT
        CHECK (SOURCE_AMOUNT > 0),

    CONSTRAINT CK_QUOTE_TARGET_AMOUNT
        CHECK (TARGET_AMOUNT > 0),

    CONSTRAINT CK_QUOTE_MARKET_RATE
        CHECK (MARKET_RATE > 0),

    CONSTRAINT CK_QUOTE_CUSTOMER_RATE
        CHECK (CUSTOMER_RATE > 0),

    CONSTRAINT CK_QUOTE_STATUS
        CHECK
        (
            STATUS IN
            (
                'OPEN',
                'SETTLED',
                'EXPIRED',
                'CANCELLED'
            )
        ),

    CONSTRAINT CK_QUOTE_DIFFERENT_WALLETS
        CHECK (SOURCE_WALLET_ID <> TARGET_WALLET_ID),

    CONSTRAINT CK_QUOTE_EXPIRY
        CHECK (EXPIRES_AT > CREATED_AT)
);


/* ============================================================
   7. QUOTE CONFIDENCE
   Owner: M2
   Input factors primarily come from M1.

   Required weights:
   Freshness   40%
   Anomaly     20%
   Provider    20%
   Stability   20%
   ============================================================ */

CREATE TABLE QUOTE_CONFIDENCE
(
    CONFIDENCE_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    QUOTE_ID VARCHAR2(36)
        NOT NULL,

    FRESHNESS_SCORE NUMBER(5,2)
        NOT NULL,

    ANOMALY_SCORE NUMBER(5,2)
        NOT NULL,

    PROVIDER_HEALTH_SCORE NUMBER(5,2)
        NOT NULL,

    STABILITY_SCORE NUMBER(5,2)
        NOT NULL,

    TOTAL_SCORE NUMBER(5,2)
        NOT NULL,

    CONFIDENCE_LEVEL VARCHAR2(20)
        NOT NULL,

    CALCULATION_DETAILS VARCHAR2(2000),

    CREATED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_QUOTE_CONFIDENCE
        PRIMARY KEY (CONFIDENCE_ID),

    CONSTRAINT FK_CONFIDENCE_QUOTE
        FOREIGN KEY (QUOTE_ID)
        REFERENCES FX_QUOTE (QUOTE_ID),

    CONSTRAINT UQ_CONFIDENCE_QUOTE
        UNIQUE (QUOTE_ID),

    CONSTRAINT CK_FRESHNESS_SCORE
        CHECK (FRESHNESS_SCORE BETWEEN 0 AND 100),

    CONSTRAINT CK_ANOMALY_SCORE
        CHECK (ANOMALY_SCORE BETWEEN 0 AND 100),

    CONSTRAINT CK_PROVIDER_SCORE
        CHECK (PROVIDER_HEALTH_SCORE BETWEEN 0 AND 100),

    CONSTRAINT CK_STABILITY_SCORE
        CHECK (STABILITY_SCORE BETWEEN 0 AND 100),

    CONSTRAINT CK_TOTAL_SCORE
        CHECK (TOTAL_SCORE BETWEEN 0 AND 100),

    CONSTRAINT CK_CONFIDENCE_LEVEL
        CHECK
        (
            CONFIDENCE_LEVEL IN
            (
                'HIGH',
                'MEDIUM',
                'LOW'
            )
        )
);


