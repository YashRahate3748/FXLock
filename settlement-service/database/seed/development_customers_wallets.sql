        DEFAULT 0
        NOT NULL,

    STATUS VARCHAR2(20)
        DEFAULT 'ACTIVE'
        NOT NULL,

    CREATED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    UPDATED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_WALLET
        PRIMARY KEY (WALLET_ID),

    CONSTRAINT FK_WALLET_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
