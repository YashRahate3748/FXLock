        NOT NULL,

    TARGET_WALLET_ID NUMBER
        NOT NULL,

    SOURCE_AMOUNT NUMBER(19,4)
        NOT NULL,

    TARGET_AMOUNT NUMBER(19,4)
        NOT NULL,

    CUSTOMER_RATE NUMBER(20,10)
