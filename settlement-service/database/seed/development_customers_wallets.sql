    PROCESSED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_PROCESSED_EVENT
        PRIMARY KEY (EVENT_ID, CONSUMER_NAME)
);


