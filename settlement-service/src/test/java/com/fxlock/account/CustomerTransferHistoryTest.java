/** Reuses isolated H2 fixtures only. The H2 ledger trigger models the already installed Oracle trigger. */
class CustomerTransferHistoryTest {
    FundingTransactionTest fixture;
    JdbcTemplate jdbc;
    SettlementService settlement;
    LedgerHistoryRepository history;
    SettlementDetailsService details;

    @BeforeEach void setup() {
        fixture=new FundingTransactionTest();
        fixture.setup();
        jdbc=fixture.jdbc;
        settlement=fixture.context.getBean(SettlementService.class);
        history=new LedgerHistoryRepository(jdbc);
        details=new SettlementDetailsService(jdbc);
        jdbc.update("INSERT INTO customer VALUES (3,'fixture-c','Customer C','ACTIVE')");
        jdbc.update("INSERT INTO customer_account(customer_id,email,login_password,account_status) VALUES (3,'c@example.test','z','ACTIVE')");
        jdbc.update("INSERT INTO wallet(wallet_id,customer_id,currency_code,balance,status) VALUES (21,2,'USD',200,'ACTIVE'),(30,3,'EUR',0,'ACTIVE')");
        jdbc.execute("""
                CREATE TABLE transaction_history (
                    transaction_history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ledger_id NUMBER NOT NULL UNIQUE REFERENCES wallet_ledger(ledger_id),
                    settlement_id VARCHAR2(36) NOT NULL REFERENCES settlement(settlement_id),
                    customer_id NUMBER NOT NULL REFERENCES customer(customer_id), customer_name VARCHAR2(150) NOT NULL,
                    wallet_id NUMBER NOT NULL REFERENCES wallet(wallet_id), currency_code VARCHAR2(3) NOT NULL,
                    amount_credited NUMBER(19,4) NOT NULL, amount_debited NUMBER(19,4) NOT NULL,
                    updated_balance NUMBER(19,4) NOT NULL, transaction_date TIMESTAMP WITH TIME ZONE NOT NULL)
                """);
        jdbc.execute("CREATE TRIGGER fixture_history AFTER INSERT ON wallet_ledger FOR EACH ROW CALL 'com.fxlock.account.CustomerTransferHistoryTest$HistoryTrigger'");
    }

    @AfterEach void close() { fixture.cleanup(); }

    String quote(int sender,int source,int target,String from,String to,String amount,String converted) {
        String id=UUID.randomUUID().toString();
        jdbc.update("""
                INSERT INTO fx_quote(quote_id,customer_id,source_wallet_id,target_wallet_id,source_currency,target_currency,
                    source_amount,target_amount,customer_rate,status,expires_at)
                VALUES (?,?,?,?,?,?,?,?,1.16766,'OPEN',DATEADD('MINUTE',5,SYSTIMESTAMP))
                """,id,sender,source,target,from,to,new BigDecimal(amount),new BigDecimal(converted));
        return id;
    }

    SettlementResponse settle(String id,String owner,String key) { return settlement.settle(id,owner,key,"fixture-correlation"); }
    BigDecimal balance(int wallet) { return jdbc.queryForObject("SELECT balance FROM wallet WHERE wallet_id=?",BigDecimal.class,wallet); }

    @Test void crossCustomerSettlementShowsSenderDebitRecipientCreditAndPrivateParticipantReceipts() {
        String id=quote(1,10,21,"EUR","USD","30","35.03");
        var result=settle(id,"fixture-a",UUID.randomUUID().toString());
        assertThat(balance(10)).isEqualByComparingTo("70");
        assertThat(balance(21)).isEqualByComparingTo("235.03");
        var sent=history.history(1,null,0,20);
        var received=history.history(2,null,0,20);
        assertThat(sent.total()).isEqualTo(1);
        assertThat(received.total()).isEqualTo(1);
        assertThat(sent.entries().getFirst().transactionType()).isEqualTo("FX_DEBIT");
        assertThat(received.entries().getFirst().transactionType()).isEqualTo("FX_CREDIT");
        assertThat(received.entries().getFirst().settlementId()).isEqualTo(result.settlementId());
        assertThat(new BigDecimal(received.entries().getFirst().updatedBalance())).isEqualByComparingTo("235.03");
        assertThat(details.getDetails(result.settlementId(),"fixture-a").ledgerEntries()).extracting(SettlementDetailsResponse.LedgerEntry::walletId).containsExactly(10L);
        assertThat(details.getDetails(result.settlementId(),"fixture-b").ledgerEntries()).extracting(SettlementDetailsResponse.LedgerEntry::walletId).containsExactly(21L);
        assertThatThrownBy(() -> details.getDetails(result.settlementId(),"fixture-c")).hasMessageContaining("SETTLEMENT_NOT_FOUND");
        var repository=new SettlementRepository(jdbc);
        assertThat(repository.findOwnedById(result.settlementId(),"fixture-b")).isPresent();
        assertThat(repository.findOwnedById(result.settlementId(),"fixture-c")).isEmpty();
        assertThat(history.history(3,null,0,20).entries()).isEmpty();
    }

    @Test void reverseAndSelfConversionSettleStoredAmountsWithoutRepricing() {
        var own=settle(quote(1,10,11,"EUR","USD","10","11.67"),"fixture-a",UUID.randomUUID().toString());
        assertThat(history.history(1,null,0,20).entries()).hasSize(2);
        assertThat(details.getDetails(own.settlementId(),"fixture-a").ledgerEntries()).hasSize(2);
        // The stored quote amounts are authoritative, irrespective of its rate field.
        settle(quote(2,21,10,"USD","EUR","20","17.06"),"fixture-b",UUID.randomUUID().toString());
        assertThat(balance(21)).isEqualByComparingTo("180");
        assertThat(balance(10)).isEqualByComparingTo("107.06");
        assertThat(history.history(1,"10",0,20).entries()).extracting(LedgerHistoryRepository.Entry::transactionType)
            .containsExactly("FX_CREDIT","FX_DEBIT");
    }

    @Test void fundingAndFxUseOneCombinedPaginationWithoutDuplicateRowsOrInventedBalances() {
        fixture.apply(UUID.randomUUID().toString(),"DEPOSIT","10");
        settle(quote(1,10,11,"EUR","USD","20","23.35"),"fixture-a",UUID.randomUUID().toString());
        fixture.apply(UUID.randomUUID().toString(),"WITHDRAWAL","5");
        assertThat(fixture.count("wallet_ledger")).isEqualTo(2);
        assertThat(fixture.count("settlement")).isEqualTo(1);
        assertThat(fixture.count("wallet_funding")).isEqualTo(2);
        var all=history.history(1,null,0,20);
        assertThat(all.total()).isEqualTo(4);
        assertThat(all.entries()).extracting(LedgerHistoryRepository.Entry::transactionType)
            .containsExactlyInAnyOrder("DEPOSIT","WITHDRAWAL","FX_DEBIT","FX_CREDIT");
        var withdrawal=all.entries().stream().filter(row -> row.transactionType().equals("WITHDRAWAL")).findFirst().orElseThrow();
        assertThat(withdrawal.ledgerId()).isNull();
        assertThat(withdrawal.settlementId()).isNull();
        assertThat(new BigDecimal(withdrawal.updatedBalance())).isEqualByComparingTo("85");
        var credit=history.history(1,"11",0,20);
        assertThat(credit.total()).isEqualTo(1);
        assertThat(credit.entries().getFirst().currency()).isEqualTo("USD");
        var first=history.history(1,null,0,2);
        var second=history.history(1,null,1,2);
        assertThat(first.hasNext()).isTrue();
        assertThat(second.hasNext()).isFalse();
        var ids=new HashSet<String>();
        first.entries().forEach(row -> assertThat(ids.add(row.entryId())).isTrue());
        second.entries().forEach(row -> assertThat(ids.add(row.entryId())).isTrue());
        assertThat(ids).hasSize(4);
        assertThat(history.history(1,null,0,2).entries()).isEqualTo(first.entries());
    }

    @Test void walletFiltersAreOwnedAndClosedWalletHistoryRemainsReadable() {
        fixture.apply(UUID.randomUUID().toString(),"DEPOSIT","1");
        jdbc.update("UPDATE wallet SET status='CLOSED' WHERE wallet_id=10");
        assertThat(history.history(1,"10",0,20).total()).isEqualTo(1);
        assertThat(history.accounts(1)).extracting(LedgerHistoryRepository.Account::walletId).containsExactly("10","11");
        assertThatThrownBy(() -> history.history(1,"21",0,20)).hasMessageContaining("ACCOUNT_NOT_FOUND");
        assertThatThrownBy(() -> history.history(1,"bad",0,20)).hasMessageContaining("INVALID_ACCOUNT");
        assertThatThrownBy(() -> history.history(1,null,-1,20)).hasMessageContaining("INVALID_PAGE");
        assertThatThrownBy(() -> history.history(1,null,0,101)).hasMessageContaining("INVALID_PAGE");
        assertThat(history.history(2,null,0,20).total()).isZero();
    }

    @ParameterizedTest @ValueSource(strings={"customer", "account", "wallet", "currency"})
    void beneficiaryEligibilityIsRecheckedWhenTheQuoteIsAccepted(String changed) {
        String id=quote(1,10,21,"EUR","USD","10","11.67");
        switch(changed) {
            case "customer" -> jdbc.update("UPDATE customer SET status='INACTIVE' WHERE customer_id=2");
            case "account" -> jdbc.update("UPDATE customer_account SET account_status='DISABLED' WHERE customer_id=2");
            case "wallet" -> jdbc.update("UPDATE wallet SET status='BLOCKED' WHERE wallet_id=21");
            case "currency" -> jdbc.update("UPDATE wallet SET currency_code='EUR' WHERE wallet_id=21");
        }
        assertThatThrownBy(() -> settle(id,"fixture-a",UUID.randomUUID().toString())).isInstanceOf(ResponseStatusException.class);
        assertThat(balance(10)).isEqualByComparingTo("100");
        assertThat(fixture.count("settlement")).isZero();
        assertThat(fixture.count("idempotency_record")).isZero();
    }

    @Test void anotherCustomersSourceAndQuoteCannotBeUsed() {
        String forged=quote(1,20,11,"EUR","USD","10","11.67");
        assertThatThrownBy(() -> settle(forged,"fixture-a",UUID.randomUUID().toString())).hasMessageContaining("WALLET_NOT_OWNED");
        String owned=quote(1,10,21,"EUR","USD","10","11.67");
        assertThatThrownBy(() -> settle(owned,"fixture-b",UUID.randomUUID().toString())).hasMessageContaining("QUOTE_NOT_OWNED");
        assertThat(fixture.count("wallet_ledger")).isZero();
    }
    @Test void fullBalanceTransferRecordsZeroAndBeneficiaryOverflowRollsBack() {
        settle(quote(1,10,21,"EUR","USD","100","116.77"),"fixture-a",UUID.randomUUID().toString());
        assertThat(balance(10)).isZero();
        assertThat(new BigDecimal(history.history(1,"10",0,20).entries().getFirst().updatedBalance())).isZero();
        fixture.apply(UUID.randomUUID().toString(),"DEPOSIT","10");
        jdbc.update("UPDATE wallet SET balance=999999999999999.9999 WHERE wallet_id=21");
        assertThatThrownBy(() -> settle(quote(1,10,21,"EUR","USD","10","11.67"),"fixture-a",UUID.randomUUID().toString()))
            .hasMessageContaining("BALANCE_LIMIT");
        assertThat(balance(10)).isEqualByComparingTo("10");
        assertThat(fixture.count("settlement")).isEqualTo(1);
    }

    @Test void historyInsertFailureRollsBackSettlementBalancesAndAllFinancialRecords() {
        jdbc.execute("ALTER TABLE transaction_history ADD CONSTRAINT reject_history CHECK (1=0)");
        assertThatThrownBy(() -> settle(quote(1,10,21,"EUR","USD","10","11.67"),"fixture-a",UUID.randomUUID().toString()))
            .isInstanceOf(RuntimeException.class);
        assertThat(balance(10)).isEqualByComparingTo("100");
        assertThat(balance(21)).isEqualByComparingTo("200");
        for (String table : new String[]{"settlement","wallet_ledger","transaction_history","idempotency_record","audit_event","outbox_event"})
            assertThat(fixture.count(table)).as(table).isZero();
    }

    @Test void idempotentC2CRetryAndOppositeConcurrentTransfersCoordinateOnTheSameWallets() throws Exception {
        String id=quote(1,10,21,"EUR","USD","10","11");
        String key=UUID.randomUUID().toString();
        var first=settle(id,"fixture-a",key);
        assertThat(settle(id,"fixture-a",key)).isEqualTo(first);
        assertThat(fixture.count("wallet_ledger")).isEqualTo(2);
        assertThat(fixture.count("transaction_history")).isEqualTo(2);
        String a=quote(1,10,21,"EUR","USD","10","11");
        String b=quote(2,21,10,"USD","EUR","20","17");
        Object[] concurrent=fixture.concurrent(() -> settle(a,"fixture-a",UUID.randomUUID().toString()),
                () -> settle(b,"fixture-b",UUID.randomUUID().toString()));
        assertThat(concurrent).allSatisfy(value -> assertThat(value).isInstanceOf(SettlementResponse.class));
        assertThat(balance(10)).isEqualByComparingTo("97");
        assertThat(balance(21)).isEqualByComparingTo("202");
        assertThat(settle(id,"fixture-a",key)).isEqualTo(first);
        assertThat(fixture.count("transaction_history")).isEqualTo(6);
        assertThatThrownBy(() -> settle(a,"fixture-a",key)).hasMessageContaining("IDEMPOTENCY_CONFLICT");
    }

    /** H2-only analogue of the user's pre-existing Oracle WALLET_LEDGER trigger. */
    public static class HistoryTrigger implements Trigger {
        private final Map<String,Integer> columns=new HashMap<>();
        @Override public void init(Connection connection,String schema,String trigger,String table,boolean before,int type) throws SQLException {
            try (var statement=connection.prepareStatement("SELECT * FROM wallet_ledger WHERE 1=0"); var rows=statement.executeQuery()) {
                var metadata=rows.getMetaData();
                for (int i=1;i<=metadata.getColumnCount();i++) columns.put(metadata.getColumnName(i).toUpperCase(Locale.ROOT),i-1);
            }
        }
        @Override public void fire(Connection connection,Object[] oldRow,Object[] row) throws SQLException {
            Object amount=row[columns.get("AMOUNT")];
            boolean credit="CREDIT".equals(row[columns.get("ENTRY_TYPE")]);
            try (var insert=connection.prepareStatement("""
                    INSERT INTO transaction_history(ledger_id,settlement_id,customer_id,customer_name,wallet_id,currency_code,
                        amount_credited,amount_debited,updated_balance,transaction_date)
                    SELECT ?,?,c.customer_id,c.full_name,w.wallet_id,?,?,?,?,?
                    FROM wallet w JOIN customer c ON c.customer_id=w.customer_id WHERE w.wallet_id=?
                    """)) {
                insert.setObject(1,row[columns.get("LEDGER_ID")]);
                insert.setObject(2,row[columns.get("SETTLEMENT_ID")]);
                insert.setObject(3,row[columns.get("CURRENCY_CODE")]);
                insert.setObject(4,credit ? amount : BigDecimal.ZERO);
                insert.setObject(5,credit ? BigDecimal.ZERO : amount);
                insert.setObject(6,row[columns.get("BALANCE_AFTER")]);
                insert.setObject(7,row[columns.get("CREATED_AT")]);
                insert.setObject(8,row[columns.get("WALLET_ID")]);
                if (insert.executeUpdate()!=1) throw new SQLException("Fixture history owner missing");
            }
        }
    }
}
