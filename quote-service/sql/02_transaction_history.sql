-- Additive extension to the supplied common schema. Run ONCE as schema owner.
-- Does not drop/reset existing tables, change wallet balances, or create settlements.
-- The owner needs CREATE TABLE, CREATE SEQUENCE (identity) and CREATE TRIGGER,
-- or a DBA can apply this with CURRENT_SCHEMA set to the intended owner.
-- In SQL*Plus / SQL Developer Run Script (F5):
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET SQLBLANKLINES ON
SET DEFINE OFF

CREATE TABLE TRANSACTION_HISTORY
(
    TRANSACTION_HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    LEDGER_ID              NUMBER NOT NULL,
    SETTLEMENT_ID          VARCHAR2(36) NOT NULL,
    CUSTOMER_ID            NUMBER NOT NULL,
    CUSTOMER_NAME          VARCHAR2(150) NOT NULL,
    WALLET_ID              NUMBER NOT NULL,
    CURRENCY_CODE          VARCHAR2(3) NOT NULL,
    AMOUNT_CREDITED        NUMBER(19,4) DEFAULT 0 NOT NULL,
    AMOUNT_DEBITED         NUMBER(19,4) DEFAULT 0 NOT NULL,
    UPDATED_BALANCE        NUMBER(19,4) NOT NULL,
    TRANSACTION_DATE       TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT PK_TRANSACTION_HISTORY PRIMARY KEY (TRANSACTION_HISTORY_ID),
    CONSTRAINT UQ_TX_HISTORY_LEDGER UNIQUE (LEDGER_ID),
    CONSTRAINT FK_TX_HISTORY_LEDGER FOREIGN KEY (LEDGER_ID)
        REFERENCES WALLET_LEDGER (LEDGER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_TX_HISTORY_SETTLEMENT FOREIGN KEY (SETTLEMENT_ID)
        REFERENCES SETTLEMENT (SETTLEMENT_ID),
    CONSTRAINT FK_TX_HISTORY_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER (CUSTOMER_ID),
    CONSTRAINT FK_TX_HISTORY_WALLET FOREIGN KEY (WALLET_ID)
        REFERENCES WALLET (WALLET_ID),
    CONSTRAINT CK_TX_HISTORY_CURRENCY CHECK (CURRENCY_CODE IN ('EUR','USD')),
    CONSTRAINT CK_TX_HISTORY_AMOUNT CHECK
    (
        (AMOUNT_CREDITED > 0 AND AMOUNT_DEBITED = 0)
        OR (AMOUNT_DEBITED > 0 AND AMOUNT_CREDITED = 0)
    ),
    CONSTRAINT CK_TX_HISTORY_BALANCE CHECK (UPDATED_BALANCE >= 0)
);

CREATE INDEX IDX_TX_HISTORY_CUSTOMER_TIME
    ON TRANSACTION_HISTORY (CUSTOMER_ID, TRANSACTION_DATE);

-- One history row per ledger entry. Each conversion normally has an EUR debit
-- row and a USD credit row. Never combine EUR and USD into one balance.
-- This trigger participates in the SAME Oracle transaction as M3's ledger insert.
CREATE TRIGGER TRG_LEDGER_TRANSACTION_HISTORY
AFTER INSERT ON WALLET_LEDGER
FOR EACH ROW
DECLARE
    v_customer_id   CUSTOMER.CUSTOMER_ID%TYPE;
    v_customer_name CUSTOMER.FULL_NAME%TYPE;
BEGIN
    SELECT C.CUSTOMER_ID, C.FULL_NAME
      INTO v_customer_id, v_customer_name
      FROM WALLET W
      JOIN CUSTOMER C ON C.CUSTOMER_ID = W.CUSTOMER_ID
     WHERE W.WALLET_ID = :NEW.WALLET_ID;

    INSERT INTO TRANSACTION_HISTORY
    (
        LEDGER_ID, SETTLEMENT_ID, CUSTOMER_ID, CUSTOMER_NAME, WALLET_ID,
        CURRENCY_CODE, AMOUNT_CREDITED, AMOUNT_DEBITED, UPDATED_BALANCE,
        TRANSACTION_DATE
    )
    VALUES
    (
        :NEW.LEDGER_ID, :NEW.SETTLEMENT_ID, v_customer_id, v_customer_name,
        :NEW.WALLET_ID, :NEW.CURRENCY_CODE,
        CASE WHEN :NEW.ENTRY_TYPE = 'CREDIT' THEN :NEW.AMOUNT ELSE 0 END,
        CASE WHEN :NEW.ENTRY_TYPE = 'DEBIT' THEN :NEW.AMOUNT ELSE 0 END,
        :NEW.BALANCE_AFTER, :NEW.CREATED_AT
    );
END;
/

-- Copy any existing ledger entries without inventing transactions.
-- The short lock prevents concurrent ledger inserts during this backfill.
LOCK TABLE WALLET_LEDGER IN EXCLUSIVE MODE;

INSERT INTO TRANSACTION_HISTORY
(
    LEDGER_ID, SETTLEMENT_ID, CUSTOMER_ID, CUSTOMER_NAME, WALLET_ID,
    CURRENCY_CODE, AMOUNT_CREDITED, AMOUNT_DEBITED, UPDATED_BALANCE,
    TRANSACTION_DATE
)
SELECT
    L.LEDGER_ID, L.SETTLEMENT_ID, C.CUSTOMER_ID, C.FULL_NAME, L.WALLET_ID,
    L.CURRENCY_CODE,
    CASE WHEN L.ENTRY_TYPE = 'CREDIT' THEN L.AMOUNT ELSE 0 END,
    CASE WHEN L.ENTRY_TYPE = 'DEBIT' THEN L.AMOUNT ELSE 0 END,
    L.BALANCE_AFTER, L.CREATED_AT
FROM WALLET_LEDGER L
JOIN WALLET W ON W.WALLET_ID = L.WALLET_ID
JOIN CUSTOMER C ON C.CUSTOMER_ID = W.CUSTOMER_ID
WHERE NOT EXISTS
    (SELECT 1 FROM TRANSACTION_HISTORY H WHERE H.LEDGER_ID = L.LEDGER_ID);

COMMIT;

-- Verify compilation: a VALID trigger is required before settlement is run.
SELECT OBJECT_NAME, STATUS FROM ALL_OBJECTS
WHERE OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
  AND OBJECT_NAME = 'TRG_LEDGER_TRANSACTION_HISTORY';
SELECT LINE, POSITION, TEXT FROM ALL_ERRORS
WHERE OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
  AND NAME = 'TRG_LEDGER_TRANSACTION_HISTORY' ORDER BY SEQUENCE;